-- ============================================================
-- Repair missing project_members table
-- ============================================================

create table if not exists public.project_members (
    id bigint generated by default as identity primary key,
    project_id bigint not null
        references public.projects(id)
        on delete cascade,
    profile_id uuid not null
        references public.profiles(id)
        on delete cascade,
    project_role text not null default 'team'
        check (project_role in ('PI', 'team')),
    created_at timestamptz not null default now(),

    unique (project_id, profile_id)
);

-- ============================================================
-- Project 01 team
-- ============================================================

insert into public.project_members
    (project_id, profile_id, project_role)
select
    pr.id,
    pf.id,
    case
        when pf.member_id = 'P1' then 'PI'
        else 'team'
    end
from public.projects pr
cross join public.profiles pf
where pr.project_code = '01'
  and pf.member_id in (
      'P1',
      'P1*',
      'P2',
      'P3',
      'P4',
      'P5',
      'P6',
      'P7',
      'P8',
      'P9',
      'P10',
      'P11'
  )
on conflict (project_id, profile_id)
do update set
    project_role = excluded.project_role;

-- ============================================================
-- Project 02 PI
-- ============================================================

insert into public.project_members
    (project_id, profile_id, project_role)
select
    pr.id,
    pf.id,
    'PI'
from public.projects pr
join public.profiles pf
    on pf.member_id = 'P3'
where pr.project_code = '02'
on conflict (project_id, profile_id)
do update set
    project_role = 'PI';

-- ============================================================
-- Security
-- ============================================================

alter table public.project_members enable row level security;

create policy "project_members_read"
on public.project_members
for select
to authenticated
using (true);

create policy "project_members_read_public"
on public.project_members
for select
to anon
using (true);

create index if not exists project_members_project_id_idx
on public.project_members(project_id);

create index if not exists project_members_profile_id_idx
on public.project_members(profile_id);